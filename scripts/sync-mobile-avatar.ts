/**
 * The phone app draws the same faces as the website (RFC §10.32). Faces are procedural
 * (apps/web/src/components/Avatar.tsx): any change to the pick lists or roll order redraws everyone,
 * so the app must never keep its own copy by hand. This script copies the drawing code from the web
 * file into apps/mobile/src/components/face.generated.tsx, swapping the SVG tags for react-native-svg.
 *
 *   bun scripts/sync-mobile-avatar.ts           write the file
 *   bun scripts/sync-mobile-avatar.ts --check   exit 1 if it is out of date
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dir, '..');
const src = readFileSync(join(root, 'apps/web/src/components/Avatar.tsx'), 'utf8').replace(/\r\n/g, '\n');
const out = join(root, 'apps/mobile/src/components/face.generated.tsx');

const start = src.indexOf('function hash(');
const end = src.indexOf('export function Avatar(');
if (start < 0 || end < 0) throw new Error('Avatar.tsx changed shape: update scripts/sync-mobile-avatar.ts');
let body = src.slice(start, end).trimEnd();

if (!body.includes("const PAPER = 'var(--paper)';")) throw new Error('PAPER constant not found in Avatar.tsx');
// the paper colour comes from the app's theme, set just before drawing
body = body.replace("const PAPER = 'var(--paper)';", "let PAPER = '#ffffff';");

const tags: Record<string, string> = {
  g: 'G', path: 'Path', circle: 'Circle', ellipse: 'Ellipse', rect: 'Rect', line: 'Line',
  polygon: 'Polygon', polyline: 'Polyline', text: 'SvgText',
};
const used = new Set<string>();
body = body.replace(/<(\/?)(g|path|circle|ellipse|rect|line|polygon|polyline|text)(?=[\s>/])/g, (_m, slash: string, tag: string) => {
  used.add(tags[tag]!);
  return `<${slash}${tags[tag]}`;
});
const imports = [...used].sort().map((n) => (n === 'SvgText' ? 'Text as SvgText' : n)).join(', ');

const file = `// GENERATED by scripts/sync-mobile-avatar.ts from apps/web/src/components/Avatar.tsx. Do not edit:
// change the web file, then run \`bun scripts/sync-mobile-avatar.ts\`.
/* eslint-disable */
import type { ReactNode } from 'react';
import type { Gender } from '@anti/shared';
import { ${imports} } from 'react-native-svg';

${body}

/** Draws one face; \`paper\` is the theme's paper colour (ink follows the Svg's \`color\`). */
export function drawFace(seed: string, gender: Gender | null, paper: string): ReactNode {
  PAPER = paper;
  return face(seed, gender);
}
`;

if (process.argv.includes('--check')) {
  const now = existsSync(out) ? readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : '';
  if (now !== file) {
    console.error('apps/mobile/src/components/face.generated.tsx is out of date: run bun scripts/sync-mobile-avatar.ts');
    process.exit(1);
  }
  console.log('faces in sync');
} else {
  writeFileSync(out, file);
  console.log(`wrote ${out}`);
}
